-- ---------------------------------------------------------------------------
-- V12: Credit Cards table — safe card metadata only
-- ---------------------------------------------------------------------------
-- Stores user-provided card metadata for PulseWallet Credit Card Intelligence.
-- NEVER stores: full card number, CVV, PIN, OTP, banking password, UPI PIN,
-- or net-banking credentials.
-- ---------------------------------------------------------------------------

CREATE TABLE credit_cards (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    issuer          VARCHAR(120) NOT NULL,
    card_name       VARCHAR(120) NOT NULL,
    last_four_digits CHAR(4)     NOT NULL,
    credit_limit    NUMERIC(19,2) NOT NULL,
    current_outstanding NUMERIC(19,2) NOT NULL DEFAULT 0,
    statement_date  DATE         NOT NULL,
    due_date        DATE         NOT NULL,
    rewards_description VARCHAR(500),
    benefits_description VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),

    CONSTRAINT chk_last_four_digits CHECK (last_four_digits ~ '^\d{4}$'),
    CONSTRAINT chk_credit_limit_positive CHECK (credit_limit > 0),
    CONSTRAINT chk_outstanding_non_negative CHECK (current_outstanding >= 0)
);

CREATE INDEX idx_credit_cards_user ON credit_cards (user_id);
