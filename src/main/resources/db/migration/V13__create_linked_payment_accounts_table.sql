-- ---------------------------------------------------------------------------
-- V13: Linked payment accounts — connection metadata only
-- ---------------------------------------------------------------------------
-- This table stores only a user-scoped placeholder/authorized-connection record.
-- It never stores banking passwords, UPI PINs, OTPs, CVV, or full card numbers.

CREATE TABLE linked_payment_accounts (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider_name       VARCHAR(120) NOT NULL,
    account_name        VARCHAR(120) NOT NULL,
    account_type        VARCHAR(30)  NOT NULL,
    status              VARCHAR(30)  NOT NULL,
    masked_identifier   VARCHAR(80)  NOT NULL,
    connected_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    last_synced_at      TIMESTAMP WITH TIME ZONE,

    CONSTRAINT chk_linked_payment_account_type CHECK (account_type IN ('BANK', 'UPI', 'PAYMENT_APP')),
    CONSTRAINT chk_linked_payment_account_status CHECK (status IN ('CONNECTED', 'DISCONNECTED'))
);

CREATE INDEX idx_linked_payment_accounts_user ON linked_payment_accounts (user_id);
